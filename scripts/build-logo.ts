/**
 * Builds the Silverpot logo data from the designer's Illustrator export (§8.9):
 *   in:  public/brand/source/silverpot-logo.svg
 *   out: src/components/brand/logo-data.ts
 *
 * Expected layer names (Illustrator "Save As → SVG", CSS Properties: Presentation Attributes):
 *   plaque                      the blue ticket shape
 *   s i l v e r p o t           one layer per letter (a group is fine, e.g. the i with its dot)
 *   star-*                      the three stars; their colour is read from the fill, not the name
 *   perch, peek  (optional)     marker shapes: where Aloom sits in the hero / peeks in the footer
 * Without markers, Aloom sits on the plaque's top edge at 88% of its width, right of the stars.
 *
 * Geometry (bounding boxes) is measured in the installed Edge, so curves are exact.
 * Run: pnpm brand:build
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from '@playwright/test';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'public', 'brand', 'source', 'silverpot-logo.svg');
const OUT = path.join(ROOT, 'src', 'components', 'brand', 'logo-data.ts');
const PAD = 14; // room for the sticker outline + offset shadow
const COLOR: Record<string, 'red' | 'yellow' | 'blue'> = {};

type Box = { x: number; y: number; w: number; h: number };
type Raw = { id: string; paths: { d: string; fill: string }[]; box: Box };

const r1 = (n: number) => Math.round(n * 10) / 10;

async function main() {
  const svg = await readFile(SRC, 'utf8');
  if (/<script|<image|xlink:href|on\w+=/i.test(svg))
    throw new Error('Logo SVG contains scripts, images or links');

  const browser = await chromium.launch({ channel: process.env.PW_CHANNEL ?? 'msedge' });
  const page = await browser.newPage();
  await page.setContent(svg);
  const raw: Raw[] = await page.evaluate(() =>
    [...document.querySelectorAll('svg > [id]')].map((el) => {
      const b = (el as SVGGraphicsElement).getBBox();
      const nodes = el.tagName === 'path' ? [el] : [...el.querySelectorAll('path')];
      return {
        id: el.id,
        paths: nodes.map((p) => ({
          d: (p.getAttribute('d') ?? '').replace(/\s+/g, ' ').trim(),
          fill: (p.getAttribute('fill') ?? el.getAttribute('fill') ?? '#000').toUpperCase(),
        })),
        box: { x: b.x, y: b.y, w: b.width, h: b.height },
      };
    }),
  );
  await browser.close();

  const plaque = raw.find((r) => r.id === 'plaque');
  if (!plaque) throw new Error('No layer named "plaque"');
  const stars = raw.filter((r) => r.id.startsWith('star'));
  if (stars.length === 0) throw new Error('No layers named "star-*"');
  const markers = new Map(raw.filter((r) => r.id === 'perch' || r.id === 'peek').map((r) => [r.id, r]));
  const letters = raw.filter((r) => r !== plaque && !stars.includes(r) && !markers.has(r.id));

  Object.assign(COLOR, { '#EC2027': 'red', '#F6DF2B': 'yellow', '#2E368F': 'blue' });
  const shapes = [plaque, ...letters, ...stars];
  const x0 = Math.min(...shapes.map((s) => s.box.x));
  const y0 = Math.min(...shapes.map((s) => s.box.y));
  const x1 = Math.max(...shapes.map((s) => s.box.x + s.box.w));
  const y1 = Math.max(...shapes.map((s) => s.box.y + s.box.h));
  const box = { x: x0 - PAD, y: y0 - PAD, w: x1 - x0 + PAD * 2, h: y1 - y0 + PAD * 2 };
  const centre = (b: Box) => ({ x: r1(b.x + b.w / 2), y: r1(b.y + b.h / 2) });

  const perchM = markers.get('perch');
  const peekM = markers.get('peek');
  const perch = perchM
    ? centre(perchM.box)
    : { x: r1(plaque.box.x + plaque.box.w * 0.88), y: r1(plaque.box.y) };
  const peek = peekM ? centre(peekM.box) : perch;

  const data = {
    viewBox: [box.x, box.y, box.w, box.h].map(r1).join(' '),
    box: { x: r1(box.x), y: r1(box.y), w: r1(box.w), h: r1(box.h) },
    plaque: { d: plaque.paths[0].d, fill: plaque.paths[0].fill, top: r1(plaque.box.y) },
    letters: letters.map((l) => ({ id: l.id, paths: l.paths })),
    stars: stars.map((s) => ({
      color: COLOR[s.paths[0].fill] ?? 'yellow',
      d: s.paths[0].d,
      fill: s.paths[0].fill,
      ...centre(s.box),
      w: r1(s.box.w),
      h: r1(s.box.h),
    })),
    perch,
    peek,
  };

  await writeFile(
    OUT,
    '// Generated by scripts/build-logo.ts from public/brand/source/silverpot-logo.svg. Do not edit by hand.\n' +
      `export const LOGO = ${JSON.stringify(data, null, 2)} as const;\n`,
  );
  console.log(
    `logo: ${letters.length} letters, ${stars.length} stars, viewBox ${data.viewBox}, perch ${perch.x},${perch.y}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
