/**
 * Lists every placeholder still on the site and exits 1 while any remain (run before launch).
 *
 * 1. Scans the data and messages for markers: `placeholder: true` facts, product `placeholder`
 *    copy, FAQ `status: 'placeholder'`, segments with `placeholder`, and `<temp>` in messages.
 * 2. Checks every marker belongs to an entry in scripts/placeholders.ts, and every entry with a
 *    `match` still has a marker, so the list and the code can't drift apart.
 *
 *   pnpm check:placeholders          print the list
 *   pnpm check:placeholders --md     also rewrite docs/PLACEHOLDERS.md
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { site } from '@/data/site';
import { products } from '@/data/products';
import { faqs } from '@/data/faq';
import { segments } from '@/data/segments';
import { PLACEHOLDERS } from './placeholders';

const markers = new Set<string>();

const walk = (o: unknown, path: string) => {
  if (!o || typeof o !== 'object') return;
  if ((o as { placeholder?: unknown }).placeholder === true) markers.add(path);
  for (const [k, v] of Object.entries(o)) walk(v, `${path}.${k}`);
};
walk(site, 'site');
for (const p of products) {
  walk(p.specs, `products.${p.id}.specs`);
  if (p.placeholder) markers.add(`products.${p.id}.placeholder`);
}
for (const f of faqs) if (f.status === 'placeholder') markers.add(`faq.${f.id}`);
for (const s of segments) if (s.placeholder) markers.add(`segments.${s.id}`);

const tempKeys = (locale: string) => {
  const keys = new Set<string>();
  const visit = (o: unknown, path: string) => {
    if (typeof o === 'string') {
      if (o.includes('<temp>')) keys.add(path);
    } else if (o && typeof o === 'object')
      for (const [k, v] of Object.entries(o)) visit(v, path ? `${path}.${k}` : k);
  };
  visit(JSON.parse(readFileSync(`messages/${locale}.json`, 'utf8')), '');
  return keys;
};
const en = tempKeys('en');
const ar = tempKeys('ar');
for (const k of en) markers.add(`messages.${k}`);

const problems: string[] = [];
for (const k of en) if (!ar.has(k)) problems.push(`messages.${k}: <temp> in en.json but not in ar.json`);
for (const k of ar) if (!en.has(k)) problems.push(`messages.${k}: <temp> in ar.json but not in en.json`);
for (const m of markers)
  if (!PLACEHOLDERS.some((e) => e.match?.test(m)))
    problems.push(`${m}: marked in code but not listed in scripts/placeholders.ts`);
for (const e of PLACEHOLDERS)
  if (e.match && ![...markers].some((m) => e.match!.test(m)))
    problems.push(`#${e.q} (${e.where}): listed, but its marker is gone. Answered? Remove the entry.`);

const count = (e: (typeof PLACEHOLDERS)[number]) =>
  e.match ? [...markers].filter((m) => e.match!.test(m)).length : 0;

console.log(`\nPlaceholders still on the site: ${PLACEHOLDERS.length} (${markers.size} markers in code)\n`);
for (const e of PLACEHOLDERS) {
  const n = count(e);
  console.log(`  #${e.q.padEnd(5)} ${e.kind.padEnd(6)} ${e.where}${n > 1 ? `  [${n} markers]` : ''}`);
  console.log(`         ${e.value}`);
}
if (problems.length) {
  console.log(`\n${problems.length} problem(s):`);
  for (const p of problems) console.log(`  ✗ ${p}`);
}

if (process.argv.includes('--md')) {
  const cell = (s: string) => s.replace(/\|/g, '\\|');
  const md = `# Placeholders

Values on the site that stand in for client answers, from "client answers v1". Numbers refer to
\`docs/CLIENT_QUESTIONS.md\`. **LIKELY** = a strong hint from the old site; **TEMP** = a stand-in
so the site looks complete. Both render in production; review mode
(\`NEXT_PUBLIC_REVIEW_MODE=true\`) marks each one "Placeholder: needs client answer".

When an answer arrives: update the data or message, remove its marker (\`placeholder: true\`,
\`status: 'placeholder'\` or \`<temp>…</temp>\`), delete its entry in \`scripts/placeholders.ts\`,
then run \`pnpm check:placeholders --md\` to refresh this file. The check exits with code 1
while anything is left, so it must pass before launch.

Generated by \`pnpm check:placeholders --md\`. ${PLACEHOLDERS.length} entries, ${markers.size} markers in code.

| # | Kind | Where | Value used |
|---|---|---|---|
${PLACEHOLDERS.map((e) => `| ${e.q} | ${e.kind} | ${cell(e.where)}${count(e) > 1 ? ` (${count(e)} markers)` : ''} | ${cell(e.value)} |`).join('\n')}

Product specs and safety stay honest: capacities, sizes, depths, pack counts, temperatures,
certificates and company numbers are never invented. Unknown specs sit behind the
"More specs on request" row with the WhatsApp "Ask about {code}" button.
`;
  writeFileSync('docs/PLACEHOLDERS.md', md);
  console.log('\nWrote docs/PLACEHOLDERS.md');
}

process.exit(PLACEHOLDERS.length || problems.length ? 1 : 0);
