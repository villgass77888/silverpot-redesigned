/**
 * Cuts the product photos out of their white studio backgrounds so they sit ON the
 * blueprint grid instead of being multiplied into it (grid lines no longer show
 * through the foil). Flood-fills near-white from the image border only, so white
 * labels and highlights inside a product stay opaque, then softens the edge by 1px.
 *
 * Reads:  public/images/products/{slug}-{n}.jpg      (written by scripts/fetch-images.ts)
 * Writes: public/images/products/cutout/{slug}-{n}.webp
 *         src/data/cutouts.generated.ts              (jpg path → cutout path + blur)
 *
 * Run: pnpm images:cutout   (after pnpm images:fetch)
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const IN_DIR = path.join(ROOT, 'public', 'images', 'products');
const OUT_DIR = path.join(IN_DIR, 'cutout');
const GEN_FILE = path.join(ROOT, 'src', 'data', 'cutouts.generated.ts');

/** A pixel counts as studio background when it is this bright and this grey. */
const MIN_CHANNEL = Number(process.env.CUT_MIN ?? 236);
const MAX_CHROMA = 14;

async function cutout(file: string) {
  const { data, info } = await sharp(path.join(IN_DIR, file))
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const n = w * h;
  const isBg = (i: number) => {
    const r = data[i * 3];
    const g = data[i * 3 + 1];
    const b = data[i * 3 + 2];
    const lo = Math.min(r, g, b);
    return lo >= MIN_CHANNEL && Math.max(r, g, b) - lo <= MAX_CHROMA;
  };

  // Flood fill from every border pixel (4-connected, iterative).
  const bg = new Uint8Array(n);
  const stack = new Int32Array(n);
  let top = 0;
  const seed = (i: number) => {
    if (!bg[i] && isBg(i)) {
      bg[i] = 1;
      stack[top++] = i;
    }
  };
  for (let x = 0; x < w; x++) {
    seed(x);
    seed((h - 1) * w + x);
  }
  for (let y = 0; y < h; y++) {
    seed(y * w);
    seed(y * w + w - 1);
  }
  while (top) {
    const i = stack[--top];
    const x = i % w;
    if (x > 0) seed(i - 1);
    if (x < w - 1) seed(i + 1);
    if (i >= w) seed(i - w);
    if (i < n - w) seed(i + w);
  }

  const alpha = Buffer.alloc(n);
  for (let i = 0; i < n; i++) alpha[i] = bg[i] ? 0 : 255;
  const soft = await sharp(alpha, { raw: { width: w, height: h, channels: 1 } })
    .blur(1)
    .extractChannel(0)
    .raw()
    .toBuffer({ resolveWithObject: true });
  const step = soft.info.channels;

  const rgba = Buffer.alloc(n * 4);
  for (let i = 0; i < n; i++) {
    rgba[i * 4] = data[i * 3];
    rgba[i * 4 + 1] = data[i * 3 + 1];
    rgba[i * 4 + 2] = data[i * 3 + 2];
    rgba[i * 4 + 3] = soft.data[i * step];
  }
  const img = sharp(rgba, { raw: { width: w, height: h, channels: 4 } });

  const out = file.replace(/\.jpe?g$/i, '.webp');
  await img.clone().webp({ quality: 88, alphaQuality: 90, effort: 5 }).toFile(path.join(OUT_DIR, out));
  const blur = await img.clone().resize(16, 16, { fit: 'inside' }).png().toBuffer();
  return {
    src: `/images/products/cutout/${out}`,
    blurDataURL: `data:image/png;base64,${blur.toString('base64')}`,
    cleared: Math.round((bg.reduce((a, b) => a + b, 0) / n) * 100),
  };
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const files = (await readdir(IN_DIR)).filter((f) => /\.jpe?g$/i.test(f)).sort();
  const map: Record<string, { src: string; blurDataURL: string }> = {};
  for (const f of files) {
    const r = await cutout(f);
    map[`/images/products/${f}`] = { src: r.src, blurDataURL: r.blurDataURL };
    console.log(`${f.padEnd(70)} background cleared: ${r.cleared}%`);
  }
  await writeFile(
    GEN_FILE,
    '// Generated by scripts/cutout-images.ts. Do not edit by hand.\n' +
      'export const cutouts: Record<string, { src: string; blurDataURL: string }> = ' +
      JSON.stringify(map, null, 2) +
      ';\n',
  );
  console.log(`\n${files.length} cutouts → ${path.relative(ROOT, OUT_DIR)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
